import { alertData } from "../data/mockData";

function Alerts() {
  const activeAlerts = alertData.filter(
    (alert) => !alert.acknowledged
  );

  const acknowledgedAlerts = alertData.filter(
    (alert) => alert.acknowledged
  );

  return (
    <div className="alerts-page">
      <div className="dashboard-heading">
        <div>
          <h2>Safety Alerts</h2>
          <p>
            Monitor and manage mine safety alerts generated by the system
          </p>
        </div>

        <div className="system-status">
          <span className="status-dot"></span>
          Alert System Active
        </div>
      </div>

      <div className="dashboard-cards">
        <div className="dashboard-card">
          <span>Total Alerts</span>
          <strong>{alertData.length}</strong>
          <small>Recorded system alerts</small>
        </div>

        <div className="dashboard-card">
          <span>Active Alerts</span>
          <strong>{activeAlerts.length}</strong>
          <small>Require attention</small>
        </div>

        <div className="dashboard-card">
          <span>Acknowledged</span>
          <strong>{acknowledgedAlerts.length}</strong>
          <small>Alerts already reviewed</small>
        </div>

        <div className="dashboard-card">
          <span>Critical Alerts</span>
          <strong>
            {
              activeAlerts.filter(
                (alert) => alert.level === "CRITICAL"
              ).length
            }
          </strong>
          <small>Highest risk level</small>
        </div>
      </div>

      <div className="dashboard-section">
        <div className="section-header">
          <div>
            <h3>Active Alerts</h3>
            <p>
              Alerts that currently require attention
            </p>
          </div>

          <span className="alert-count">
            {activeAlerts.length} Active
          </span>
        </div>

        {activeAlerts.length === 0 ? (
          <div className="empty-state">
            <h3>No active alerts</h3>
            <p>
              All current safety alerts have been acknowledged.
            </p>
          </div>
        ) : (
          <div className="alerts-page-list">
            {activeAlerts.map((alert) => (
              <div
                className="alert-page-item"
                key={alert.id}
              >
                <div className="alert-page-main">
                  <div className="alert-indicator"></div>

                  <div>
                    <div className="alert-page-title">
                      <strong>{alert.location}</strong>

                      <span
                        className={`risk-${alert.level.toLowerCase()}`}
                      >
                        {alert.level}
                      </span>
                    </div>

                    <p>{alert.message}</p>

                    <small>
                      Alert ID: {alert.id} • {alert.timestamp}
                    </small>
                  </div>
                </div>

                <button
                  type="button"
                  className="acknowledge-button"
                >
                  Acknowledge
                </button>
              </div>
            ))}
          </div>
        )}
      </div>

      <div className="dashboard-section">
        <h3>Alert Response Levels</h3>

        <div className="alert-level-grid">
          <div>
            <span className="risk-safe">SAFE</span>
            <p>
              Normal operating conditions. Continue regular monitoring.
            </p>
          </div>

          <div>
            <span className="risk-watch">WATCH</span>
            <p>
              Increased monitoring should be considered.
            </p>
          </div>

          <div>
            <span className="risk-warning">WARNING</span>
            <p>
              Increased risk detected. Safety teams should investigate.
            </p>
          </div>

          <div>
            <span className="risk-critical">CRITICAL</span>
            <p>
              Immediate safety attention may be required.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}

export default Alerts;